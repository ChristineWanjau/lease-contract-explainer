"""Contract analysis: structured summary and per-clause risk flags.

Structured output is done with a prompt + Pydantic validation rather than
``with_structured_output`` so the exact same code path runs against Ollama in
production and against LangChain's fake chat models in tests.

Citations are never generated by the model: each flag is tied to the clause
chunk it was produced from, and the quote is that chunk's stored text.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterator
from typing import Literal

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field, ValidationError

from lce.packs import Pack, RiskCategory
from lce.splitter import Chunk

DISCLAIMER = (
    "This is an automated explanation, not legal advice. It may be incomplete or wrong. "
    "For important decisions, consult a qualified lawyer."
)

MAX_ATTEMPTS = 2  # first try + one retry


class AnalysisError(Exception):
    """The model could not produce valid output."""


_SUMMARY_SYSTEM = """You explain contracts in plain language to the person about to sign.
Use only what the contract says. If something is not stated, write "Not stated".
Reply with a single JSON object and nothing else, matching this JSON schema:
{schema}"""

_THINK = re.compile(r"<think>.*?</think>", re.DOTALL)
_FENCE = re.compile(r"```(?:json)?\s*(.*?)```", re.DOTALL)


def _contract_text(chunks: list[Chunk]) -> str:
    parts = []
    for c in chunks:
        label = f"Clause {c.clause}" if c.clause else "Preamble"
        parts.append(f"[{label}, p. {c.page}]\n{c.text}")
    return "\n\n".join(parts)


def _parse_json(text: str) -> dict:
    text = _THINK.sub("", text).strip()
    fenced = _FENCE.search(text)
    if fenced:
        text = fenced.group(1).strip()
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end < start:
        raise ValueError("no JSON object in reply")
    return json.loads(text[start : end + 1])


def summarize(llm: BaseChatModel, chunks: list[Chunk], pack: Pack) -> dict:
    """Ask the model for the pack's summary fields, validating with one retry."""
    model = pack.summary_model()
    messages = [
        SystemMessage(_SUMMARY_SYSTEM.format(schema=json.dumps(model.model_json_schema()))),
        HumanMessage(f"Contract:\n\n{_contract_text(chunks)}"),
    ]
    last_error: Exception | None = None
    for _ in range(MAX_ATTEMPTS):
        reply = llm.invoke(messages)
        try:
            return model.model_validate(_parse_json(str(reply.content))).model_dump()
        except (ValueError, ValidationError) as e:
            last_error = e
    raise AnalysisError("The model returned an invalid summary twice.") from last_error


# ---------------------------------------------------------------- risk flags


class _ModelFlag(BaseModel):
    """What the model is asked to return for one risk in a clause."""

    category: str
    severity: Literal["high", "medium", "low"]
    explanation: str = Field(description="Why this matters to the signer, in plain language")
    question_to_ask: str = Field(description="A question to ask the other party before signing")


class _ModelFlags(BaseModel):
    flags: list[_ModelFlag]


class Citation(BaseModel):
    clause: str | None
    page: int
    quote: str


class RiskFlag(BaseModel):
    category: str
    category_label: str
    severity: Literal["high", "medium", "low"]
    explanation: str
    question_to_ask: str
    citations: list[Citation]


_RISK_SYSTEM = """You review one clause of a contract for the person about to sign it.
Decide whether the clause matches any of these risk categories:
{categories}

Only flag a category if this clause clearly matches it. Most clauses match none.
Severity: "high" can cost the signer a lot of money or freedom; "medium" is unfavourable
but manageable; "low" is worth knowing about.
Reply with a single JSON object and nothing else, matching this JSON schema:
{schema}
Use {{"flags": []}} if nothing matches."""


def _classify_clause(
    llm: BaseChatModel, chunk: Chunk, categories: dict[str, RiskCategory]
) -> list[RiskFlag]:
    category_list = "\n".join(f"- {c.id}: {c.description}" for c in categories.values())
    label = f"Clause {chunk.clause}" if chunk.clause else "Preamble"
    messages = [
        SystemMessage(
            _RISK_SYSTEM.format(
                categories=category_list, schema=json.dumps(_ModelFlags.model_json_schema())
            )
        ),
        HumanMessage(f"Clause to review ({label}, p. {chunk.page}):\n\n{chunk.text}"),
    ]
    last_error: Exception | None = None
    for _ in range(MAX_ATTEMPTS):
        reply = llm.invoke(messages)
        try:
            parsed = _ModelFlags.model_validate(_parse_json(str(reply.content)))
            break
        except (ValueError, ValidationError) as e:
            last_error = e
    else:
        raise AnalysisError(f"Invalid risk output for {label}.") from last_error

    citation = Citation(clause=chunk.clause, page=chunk.page, quote=chunk.text)
    seen: set[str] = set()
    out: list[RiskFlag] = []
    for f in parsed.flags:
        category = categories.get(f.category)
        if category is None or category.id in seen:  # unknown or duplicate category
            continue
        seen.add(category.id)
        out.append(
            RiskFlag(
                category=category.id,
                category_label=category.label,
                severity=f.severity,
                explanation=f.explanation,
                question_to_ask=f.question_to_ask,
                citations=[citation],
            )
        )
    return out


class RiskScanResult(BaseModel):
    skipped_clauses: list[str | None] = []


def find_risks(
    llm: BaseChatModel,
    chunks: list[Chunk],
    categories: list[RiskCategory],
    result: RiskScanResult,
) -> Iterator[RiskFlag]:
    """Yield risk flags clause by clause. Clauses whose output is invalid twice are
    recorded in ``result.skipped_clauses`` instead of stopping the scan."""
    by_id = {c.id: c for c in categories}
    for chunk in chunks:
        if chunk.clause is None:  # preamble: parties and premises, not obligations
            continue
        try:
            yield from _classify_clause(llm, chunk, by_id)
        except AnalysisError:
            result.skipped_clauses.append(chunk.clause)
